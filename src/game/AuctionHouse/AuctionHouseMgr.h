// 拍卖操作错误码（对应 SMSG_AUCTION_COMMAND_RESULT）
enum AuctionError
{
    AUCTION_OK                          = 0,                // depends on enum AuctionAction (操作成功，具体含义取决于 AuctionAction)
    AUCTION_ERR_INVENTORY               = 1,                // depends on enum InventoryChangeResult (背包操作错误)
    AUCTION_ERR_DATABASE                = 2,                // ERR_AUCTION_DATABASE_ERROR (default) (数据库错误)
    AUCTION_ERR_NOT_ENOUGH_MONEY        = 3,                // ERR_NOT_ENOUGH_MONEY (金币不足)
    AUCTION_ERR_ITEM_NOT_FOUND          = 4,                // ERR_ITEM_NOT_FOUND (未找到物品)
    AUCTION_ERR_HIGHER_BID              = 5,                // ERR_AUCTION_HIGHER_BID (已有更高出价)
    AUCTION_ERR_BID_INCREMENT           = 7,                // ERR_AUCTION_BID_INCREMENT (加价幅度不足)
    AUCTION_ERR_BID_OWN                 = 10,               // ERR_AUCTION_BID_OWN (不能竞拍自己的拍卖品)
    AUCTION_ERR_RESTRICTED_ACCOUNT      = 13                // ERR_RESTRICTED_ACCOUNT (受限账号)
};

// 拍卖行为类型
enum AuctionAction
{
    AUCTION_STARTED     = 0,                                // ERR_AUCTION_STARTED (上架拍卖)
    AUCTION_REMOVED     = 1,                                // ERR_AUCTION_REMOVED (取消拍卖)
    AUCTION_BID_PLACED  = 2                                 // ERR_AUCTION_BID_PLACED (竞拍出价)
};

/// 单条拍卖记录实体，保存物品、卖家、竞价、一口价、到期时间与所属拍卖行信息
struct AuctionEntry
{
    uint32 Id = 0;                                          // 拍卖条目唯一 ID
    uint32 itemGuidLow = 0;                                 // can be 0 after send won mail with item (拍卖物品低位 GUID，中标发邮件后清零)
    uint32 itemTemplate = 0;                                // 物品模板 ID
    uint32 itemCount = 0;                                   // 物品堆叠数量
    int32 itemRandomPropertyId = 0;                         // 物品随机属性 ID
    uint32 owner = 0;                                       // player low guid, can be 0 for server generated auction (卖家低位 GUID；0 表示系统/机器人拍卖)
    std::wstring ownerName;                                 // cache name for sorting (缓存的卖家宽字符名称，用于排序)
    uint32 startbid = 0;                                    // start minimal bid value (起拍价)
    uint32 bid = 0;                                         // current bid, =0 meaning no bids (当前最高出价，0 表示尚无人竞拍)
    uint32 buyout = 0;                                      // 一口价（0 表示无一口价）
    time_t expireTime = 0;                                  // 拍卖到期时间戳
    uint32 bidder = 0;                                      // current bidder player lowguid, can be 0 if bid generated by server, use 'bid'!=0 for check bid existance (当前竞拍者低位 GUID)
    uint32 deposit = 0;                                     // deposit can be calculated only when creating auction (保管费/押金，仅上架时计算)
    AuctionHouseEntry const* auctionHouseEntry = nullptr;   // in AuctionHouse.dbc (所属拍卖行 DBC 条目)

    // helpers (辅助方法)
    uint32 GetHouseId() const { return auctionHouseEntry->houseId; }
    uint32 GetHouseFaction() const { return auctionHouseEntry->faction; }
    /// 计算拍卖手续费（按当前成交价与拍卖行税率）
    uint32 GetAuctionCut() const;
    /// 计算最小加价幅度
    uint32 GetAuctionOutBid() const;
    /// 将拍卖条目序列化写入世界数据包
    bool BuildAuctionInfo(WorldPacket& data) const;
    /// 从数据库删除本条拍卖记录
    void DeleteFromDB() const;
    /// 将本条拍卖记录插入数据库
    void SaveToDB() const;
    /// 拍卖成交结算：发送待收款/成交/中标邮件并移除拍卖条目
    void AuctionBidWinning(Player* newbidder = nullptr);

    // -1,0,+1 order result (按指定列比较两个拍卖条目的排序顺序，返回 -1/0/+1)
    int CompareAuctionEntry(uint32 column, const AuctionEntry* auc, Player* viewPlayer) const;

    /// 更新竞拍出价（处理加价或一口价买断，退款给前一竞拍者）
    bool UpdateBid(uint32 newbid, Player* newbidder = nullptr);// true if normal bid, false if buyout, bidder==nullptr for generated bid (普通竞价返回 true，一口价成交返回 false)
};

// this class is used as auctionhouse instance (单个拍卖行实例对象，管理同阵营/中立拍卖行中的所有挂单)
class AuctionHouseObject
{
    public:
        AuctionHouseObject() {}
        ~AuctionHouseObject()
        {
            for (AuctionEntryMap::const_iterator itr = AuctionsMap.begin(); itr != AuctionsMap.end(); ++itr)
                delete itr->second;
        }

        typedef std::map<uint32, AuctionEntry*> AuctionEntryMap;
        typedef std::pair<AuctionEntryMap::const_iterator, AuctionEntryMap::const_iterator> AuctionEntryMapBounds;

        uint32 GetCount() const { return AuctionsMap.size(); }

        AuctionEntryMap const& GetAuctions() const { return AuctionsMap; }
        AuctionEntryMapBounds GetAuctionsBounds() const {return AuctionEntryMapBounds(AuctionsMap.begin(), AuctionsMap.end()); }

        /// 向拍卖行内存映射中添加拍卖条目
        void AddAuction(AuctionEntry* ah)
        {
            MANGOS_ASSERT(ah);
            AuctionsMap[ah->Id] = ah;
        }

        /// 按拍卖 ID 查找拍卖条目
        AuctionEntry* GetAuction(uint32 id) const
        {
            AuctionEntryMap::const_iterator itr = AuctionsMap.find(id);
            return itr != AuctionsMap.end() ? itr->second : nullptr;
        }

        /// 从内存中移除指定 ID 的拍卖条目
        bool RemoveAuction(uint32 id) { return !!AuctionsMap.erase(id); }

        /// 周期更新：处理已到期的拍卖成交与流拍
        void Update();

        /// 填充玩家正在竞拍的物品列表数据包
        void BuildListBidderItems(WorldPacket& data, Player* player, uint32 listfrom, uint32& count, uint32& totalcount);
        /// 填充玩家自己寄售的物品列表数据包
        void BuildListOwnerItems(WorldPacket& data, Player* player, uint32 listfrom, uint32& count, uint32& totalcount);

        /// 创建新拍卖条目并持久化到数据库
        AuctionEntry* AddAuction(AuctionHouseEntry const* auctionHouseEntry, Item* newItem, uint32 etime, uint32 bid, uint32 buyout = 0, uint32 deposit = 0, Player* pl = nullptr);
    private:
        AuctionEntryMap AuctionsMap;
};

