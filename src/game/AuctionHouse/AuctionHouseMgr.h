// 拍卖行阵营归属类型（联盟、部落、中立/互通）
enum AuctionHouseType
{
    AUCTION_HOUSE_ALLIANCE  = 0,
    AUCTION_HOUSE_HORDE     = 1,
    AUCTION_HOUSE_NEUTRAL   = 2
};

#define MAX_AUCTION_HOUSE_TYPE 3

/// 全局拍卖行管理器，统筹三方拍卖行实例、寄售物品缓存及数据库加载
class AuctionHouseMgr
{
    public:
        AuctionHouseMgr();
        ~AuctionHouseMgr();

        typedef std::unordered_map<uint32, Item*> ItemMap;

        // Removes the auctions of a character that is being deleted and takes back its bids. Sends mail, so it must
        // not run inside an open database transaction.
        // 清理正在删除角色的拍卖与出价（内部会发送退款邮件，不得在已开启的数据库事务中调用）
        void RemovePlayerAuctions(ObjectGuid playerGuid);

        AuctionHouseObject* GetAuctionsMap(AuctionHouseType houseType) { return &mAuctions[houseType]; }
        AuctionHouseObject* GetAuctionsMap(AuctionHouseEntry const* house);

        /// 根据物品低位 GUID 获取寄售物品对象
        Item* GetAItem(uint32 id)
        {
            ItemMap::const_iterator itr = mAitems.find(id);
            if (itr != mAitems.end())
            {
                return itr->second;
            }
            return nullptr;
        }

        // auction messages (拍卖系统邮件通知)
        void SendAuctionWonMail(AuctionEntry* auction);
        void SendAuctionSalePendingMail(AuctionEntry* auction);
        static void SendAuctionSuccessfulMail(AuctionEntry* auction);
        void SendAuctionExpiredMail(AuctionEntry* auction);
        /// 计算上架保管费（押金）
        static uint32 GetAuctionDeposit(AuctionHouseEntry const* entry, uint32 time, Item* pItem);

        /// 获取拍卖行所属阵营（ALLIANCE/HORDE/0）
        static uint32 GetAuctionHouseTeam(AuctionHouseEntry const* house);
        /// 根据拍卖师单位或玩家查找对应拍卖行 DBC 配置
        static AuctionHouseEntry const* GetAuctionHouseEntry(Unit* unit);

    public:
        // load first auction items, because of check if item exists, when loading
        // 启动加载：需先加载拍卖物品再加载拍卖记录，以便校验物品是否存在
        void LoadAuctionItems();
        void LoadAuctions();

        /// 注册/移除内存中的寄售物品实例
        void AddAItem(Item* it);
        bool RemoveAItem(uint32 id);

        /// 驱动各拍卖行更新到期条目
        void Update();

    private:
        AuctionHouseObject  mAuctions[MAX_AUCTION_HOUSE_TYPE];

        ItemMap             mAitems;
};

#define sAuctionMgr MaNGOS::Singleton<AuctionHouseMgr>::Instance()

